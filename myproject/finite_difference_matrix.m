function A = finite_difference_matrix(n, dx)
% FINITE_DIFFERENCE_MATRIX 构建用于欧拉-伯努利梁的有限差分矩阵
%
% 输入:
%   n  - 节点数量
%   dx - 空间步长
% 输出:
%   A  - 差分矩阵 (n x n)
%
% 边界条件:
%   x=0 (根部): 严格固定端 (w=0, dw/dx=0)
%   x=L (尖端): 自由端 (d2w/dx2=0, d3w/dx3=0)

    A = zeros(n, n);
    
    % ==== 严格固定端边界 (w=0 和 dw/dx=0) ====
    % 节点1: w(0)=0
    A(1, 1) = 1; 
    
    % 节点2: dw/dx(0)=0 => (w2 - w0)/(2dx) = 0 => w0 = w2
    % d^2w/dx^2 = (w2 - 2w1 + w0)/dx^2 = (w2 - 2w1 + w2)/dx^2
    % 但这里我们要直接施加约束。
    % 常见的处理方式是前向差分：(-3w1 + 4w2 - w3) / 2dx = 0
    % 或者更简单的：(w2 - w1)/dx = 0 (一阶精度)
    % 原代码使用的是：A(2, 1:2) = [-1, 1]/dx; 即 w2 - w1 = 0
    A(2, 1:2) = [-1, 1]/dx; 
    
    % 内部节点 (四阶导数 d4w/dx4)
    % 系数: [1, -4, 6, -4, 1] / dx^4
    for i = 3:n-2
        A(i, i-2:i+2) = [1, -4, 6, -4, 1];
    end
    
    % 自由端边界 (弯矩=0, 剪力=0)
    % 节点n-1: d²w/dx²=0 => w_{n-2} - 2w_{n-1} + w_n = 0
    A(n-1, n-2:n) = [1, -2, 1]; 
    
    % 节点n: d³w/dx³=0 => -w_{n-3} + 3w_{n-2} - 3w_{n-1} + w_n = 0
    A(n, n-3:n) = [-1, 3, -3, 1]; 
    
    A = A / dx^4; 
end
